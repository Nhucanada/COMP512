#!/usr/bin/env python3
"""
COMP 512 PA2: Island Log & Consensus Consistency Verifier
Audits output log files generated by TreasureIslandApp / TreasureIslandAppAuto:
1. Compares move ordering across all player logs (gameid-playernum.log)
2. Ignores process header line and verifies STRICT TOTAL ORDER agreement
3. Verifies no dropped moves and counts per-player move share (Fairness)
4. Checks start/end display snapshots (gameid-playernum-display.log)
"""

import os
import sys
import glob
import argparse
from pathlib import Path

def parse_island_log(log_path):
    moves = []
    header = None
    with open(log_path, "r", encoding="utf-8", errors="ignore") as f:
        for idx, line in enumerate(f):
            line = line.strip()
            if not line:
                continue
            if idx == 0:
                header = line
            else:
                moves.append(line)
    return header, moves

def verify_logs(log_dir=".", gameid=None, expected_players=None):
    log_dir = Path(log_dir).resolve()
    
    # Locate log files
    pattern = f"{gameid}-*.log" if gameid else "game-*-*.log"
    candidate_files = list(log_dir.glob(pattern))
    
    # Filter out display logs and processinfo logs
    island_logs = []
    for f in candidate_files:
        name = f.name
        if "-display.log" in name or "-processinfo-" in name:
            continue
        island_logs.append(f)

    island_logs.sort(key=lambda p: p.name)

    if not island_logs:
        print(f"[ERROR] No Island log files found in {log_dir} matching {pattern}")
        return False

    print("\n" + "=" * 65)
    print("COMP 512 PA2: PAXOS TOTAL ORDER & LOG CONSISTENCY AUDIT")
    print(f"Directory: {log_dir}")
    print(f"Log Files Found ({len(island_logs)}): {[f.name for f in island_logs]}")
    print("=" * 65)

    parsed = {}
    for f in island_logs:
        header, moves = parse_island_log(f)
        parsed[f.name] = {"header": header, "moves": moves, "count": len(moves)}
        print(f"  + {f.name}: {len(moves)} moves recorded (Header: {header})")

    # 1. Total Order Agreement Check
    first_name = island_logs[0].name
    baseline_moves = parsed[first_name]["moves"]
    mismatch = False

    for f in island_logs[1:]:
        other_name = f.name
        other_moves = parsed[other_name]["moves"]

        if len(baseline_moves) != len(other_moves):
            print(f"[FAIL] Move count mismatch: {first_name} has {len(baseline_moves)} vs {other_name} has {len(other_moves)}")
            mismatch = True
            min_len = min(len(baseline_moves), len(other_moves))
            for i in range(min_len):
                if baseline_moves[i] != other_moves[i]:
                    print(f"       First divergence at move {i+1}: '{baseline_moves[i]}' vs '{other_moves[i]}'")
                    break
        else:
            diffs = [(i, m1, m2) for i, (m1, m2) in enumerate(zip(baseline_moves, other_moves)) if m1 != m2]
            if diffs:
                mismatch = True
                print(f"[FAIL] Total order divergence between {first_name} and {other_name} ({len(diffs)} differences):")
                for i, m1, m2 in diffs[:5]:
                    print(f"       Turn {i+1}: {first_name}='{m1}' != {other_name}='{m2}'")
            else:
                print(f"[PASS] Exact total order match: {first_name} == {other_name} ({len(baseline_moves)} moves)")

    # 2. Per-Player Move Distribution (Fairness Analysis)
    print("\n--- Move Distribution & Fairness Analysis ---")
    player_counts = {}
    for m in baseline_moves:
        parts = m.split()
        if len(parts) >= 5 and parts[0] == "Move" and parts[2] == "player":
            try:
                p_num = int(parts[4])
                player = f"Player {chr(ord('A') + p_num - 1)}"
            except ValueError:
                player = parts[4]
        else:
            player = parts[0] if parts else "UNKNOWN"
        player_counts[player] = player_counts.get(player, 0) + 1

    total_moves = len(baseline_moves)
    for p in sorted(player_counts.keys()):
        cnt = player_counts[p]
        pct = (cnt / total_moves * 100) if total_moves > 0 else 0
        print(f"  Player {p}: {cnt:>4} moves ({pct:>5.1f}%)")

    # 3. Check Display Snapshots (if present)
    display_logs = list(log_dir.glob("*-display.log"))
    if display_logs:
        print(f"\n--- Island Map End-State Snapshot Audit ({len(display_logs)} display logs) ---")
        end_maps = {}
        for df in sorted(display_logs):
            content = df.read_text(errors="ignore").strip()
            # Capture the last map display block
            end_maps[df.name] = content[-1500:] if len(content) > 1500 else content

        first_df = display_logs[0].name
        for df in display_logs[1:]:
            if end_maps[first_df] == end_maps[df.name]:
                print(f"[PASS] End-state map display identical: {first_df} == {df.name}")
            else:
                print(f"[WARN] End-state map display differs between {first_df} and {df.name}")

    print("\n" + "=" * 65)
    if not mismatch and total_moves > 0:
        print("VERIFICATION RESULT: SUCCESS! Strict Total Order Consensus Certified.")
        print("=" * 65 + "\n")
        return True
    else:
        print("VERIFICATION RESULT: FAILED! Total Order Invariant Violations Detected.")
        print("=" * 65 + "\n")
        return False

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="COMP 512 PA2 Island Log Verifier")
    parser.add_argument("--dir", default=".", help="Directory containing log files (default: .)")
    parser.add_argument("--gameid", help="Game ID prefix (optional)")
    args = parser.parse_args()

    success = verify_logs(args.dir, args.gameid)
    sys.exit(0 if success else 1)
